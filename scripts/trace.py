"""Build the requirement -> code -> test mapping and check it is complete.

    uv run python scripts/trace.py

Reads requirement IDs from docs/PRD.md, "# REQ: <ID>" comments from the source,
and @pytest.mark.req("<ID>") markers from the tests. Writes docs/TRACEABILITY.md.

Exit code 1 if a requirement has no test, or if code or a test names an ID that
is not in the PRD.
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PRD = ROOT / "docs" / "PRD.md"
OUTPUT = ROOT / "docs" / "TRACEABILITY.md"
SOURCE_FILES = sorted((ROOT / "src").rglob("*.py")) + sorted((ROOT / "src").rglob("*.sql")) + [ROOT / "pyproject.toml"]
TEST_FILES = sorted((ROOT / "tests").glob("test_*.py"))

REQUIREMENT_ROW = re.compile(r"^\| ((?:FR|BR|IDM|SEC|NFR)-\d+) \| (.+?) \|$")
REQ_COMMENT = re.compile(r"REQ:\s*((?:[A-Z]+-\d+)(?:\s*,\s*[A-Z]+-\d+)*)")


def read_requirements() -> dict[str, str]:
    """{ID: text} for every requirement row in the PRD tables."""
    requirements = {}
    for line in PRD.read_text().splitlines():
        match = REQUIREMENT_ROW.match(line)
        if match:
            requirements[match.group(1)] = match.group(2)
    return requirements


def read_code_tags() -> dict[str, list[str]]:
    """{ID: ["src/assistance/money.py:16", ...]} from REQ comments."""
    tags: dict[str, list[str]] = {}
    for path in SOURCE_FILES:
        for number, line in enumerate(path.read_text().splitlines(), start=1):
            match = REQ_COMMENT.search(line)
            if match:
                for requirement_id in re.split(r"\s*,\s*", match.group(1)):
                    tags.setdefault(requirement_id, []).append(f"{path.relative_to(ROOT)}:{number}")
    return tags


def read_test_tags() -> dict[str, list[str]]:
    """{ID: ["test_money.py::test_zero_is_refused", ...]} from @pytest.mark.req(...) decorators."""
    tags: dict[str, list[str]] = {}
    for path in TEST_FILES:
        for node in ast.walk(ast.parse(path.read_text())):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for decorator in node.decorator_list:
                is_req_marker = (
                    isinstance(decorator, ast.Call)
                    and isinstance(decorator.func, ast.Attribute)
                    and decorator.func.attr == "req"
                )
                if is_req_marker:
                    for argument in decorator.args:
                        tags.setdefault(argument.value, []).append(f"{path.name}::{node.name}")
    return tags


def main() -> int:
    requirements = read_requirements()
    code = read_code_tags()
    tests = read_test_tags()

    lines = [
        "# Requirement traceability",
        "",
        "Generated by `uv run python scripts/trace.py`. Do not edit by hand.",
        "",
        "| ID | Requirement | Code | Tests |",
        "|---|---|---|---|",
    ]
    for requirement_id, text in requirements.items():
        code_cell = "<br>".join(f"`{place}`" for place in code.get(requirement_id, [])) or "–"
        test_cell = "<br>".join(f"`{name}`" for name in tests.get(requirement_id, [])) or "**none**"
        lines.append(f"| {requirement_id} | {text} | {code_cell} | {test_cell} |")
    OUTPUT.write_text("\n".join(lines) + "\n")

    untested = [r for r in requirements if r not in tests]
    no_code_tag = [r for r in requirements if r not in code]
    unknown = sorted((set(code) | set(tests)) - set(requirements))

    tagged_tests = {name for names in tests.values() for name in names}
    print(f"{len(requirements)} requirements, {len(tagged_tests)} tagged test functions, wrote {OUTPUT.relative_to(ROOT)}")
    if no_code_tag:
        print(f"note: no REQ comment in code for: {', '.join(no_code_tag)}")
    if untested:
        print(f"FAIL: no test for: {', '.join(untested)}")
    if unknown:
        print(f"FAIL: IDs that are not in the PRD: {', '.join(unknown)}")
    return 1 if untested or unknown else 0


if __name__ == "__main__":
    sys.exit(main())
